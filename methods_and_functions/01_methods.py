#append
list = [1,2,3,4,5]
list.append(6)
print(list)

#count
list = [1,2,3,4,5]
print(list.count(2))

#extend
list = [1,2,3,4,5]
list.extend([6,7,8])
print(list)

#insert
list = [1,2,3,4,5]
list.insert(0,6)
print(list)

#pop
list = [10,20,30,40]
list.pop(1)
print(list)

#remove
list = [10, 20, 30, 20]
list.remove(20)
print(list)


#reverse
list = [1,2,3,4,5]
list.reverse()
print(list)

#sort
list = [5, 2, 8, 1, 3]
list.sort()
print(list)